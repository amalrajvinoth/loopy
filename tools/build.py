#!/usr/bin/env python3
"""Build the small files the site serves from the readable files in src/.

    src/loopy.js   ->  loopy.js    (minified; loopy-report.js, loopy-backup.js, loopy-sheet.js, loopy-levels.js, loopy-install.js the same way)
    src/loopy.css  ->  loopy.css   (minified; print.css the same way)
    src/sw.js      ->  sw.js       (minified, with the list of files to save for offline use and their hash)
    src/fonts/*    ->  fonts/*     (only the letters loopy uses, weights 400 to 700; with --fonts)

Then it refreshes every page's security policy (tools/csp.py).

Run after editing anything in src/:   python3 tools/build.py
Also rebuild the fonts:               python3 tools/build.py --fonts
Check without changing anything (used by the GitHub check):   python3 tools/build.py --check

Needs the minifiers in tools/requirements.txt. The --fonts step also needs fonttools and brotli.
Never edit loopy.js or loopy.css by hand: the next build overwrites them and the check fails.
"""
import hashlib, io, json, pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

# Letters the fonts keep: English, German (Ä Ö Ü ß), × ÷ · ° ±, dashes, quotes, the euro and minus signs.
# Any other letter still shows, in the device's own font. To add one, add it here and to the
# unicode-range of the three "-latin" @font-face rules in src/loopy.css, then run: python3 tools/build.py --fonts
UNICODES = ("U+0020-007E, U+00A0, U+00A9, U+00AB, U+00B0-00B1, U+00B7, U+00BB, U+00C4, U+00D6-00D7, U+00DC, "
            "U+00DF, U+00E4, U+00F6-00F7, U+00FC, U+2013-2014, U+2018-201A, U+201C-201E, U+2022, U+2026, "
            "U+20AC, U+2212")
# font file -> the weights the site uses (the rest of each font's weight range is dropped)
# atkinson-latin.woff2 is Atkinson Hyperlegible Next, the "Easier to read" font (only loaded when that setting is on).
FONTS = {"lexend-latin.woff2": (400, 700), "fredoka-latin.woff2": (600, 700), "atkinson-latin.woff2": (400, 700)}


# src/<name> -> <name> at the root, minified. loopy.js and loopy.css load on every page; the loopy-*.js
# parts and print.css load only when they are needed (see Loopy.load in src/loopy.js).
BUILT = ["loopy.js", "loopy.css", "loopy-report.js", "loopy-backup.js", "loopy-sheet.js", "loopy-levels.js", "loopy-install.js", "print.css"]


def banner(name):
    return f"/* loopy: built from src/{name} by tools/build.py. Do not edit this file, edit the source. */\n"


def minified():
    try:
        import rjsmin, rcssmin
    except ImportError:
        sys.exit("Missing minifiers. Run: python3 -m pip install --require-hashes --no-binary :all: "
                 "-r tools/requirements.txt")
    out = {}
    for name in BUILT:
        text = (SRC / name).read_text(encoding="utf-8")
        small = rcssmin.cssmin(text) if name.endswith(".css") else rjsmin.jsmin(text)
        out[name] = banner(name) + small.strip() + "\n"
    return out


# Files the offline helper (sw.js) saves on the device: everything a page loads. Not saved: the
# folders and file types below, which are for people working on loopy, not for the site.
SKIP_DIRS = {".git", ".github", ".claude", ".claude-plugin", ".well-known", "docs", "plugins", "src", "tools", "node_modules"}
SAVE = {".html", ".js", ".css", ".woff2", ".png", ".svg", ".webmanifest"}


def offline_files():
    """{"math/plus-minus/": path, ...} for every file the site serves to a visitor."""
    out = {}
    for p in sorted(ROOT.rglob("*")):
        rel = p.relative_to(ROOT)
        if not p.is_file() or p.suffix not in SAVE or SKIP_DIRS & set(rel.parts) or rel.as_posix() == "sw.js":
            continue
        url = rel.as_posix()
        if p.name == "index.html":
            url = url[:-len("index.html")] or "./"
        out[url] = p
    return out


def service_worker():
    """sw.js: the minified src/sw.js after VERSION (a hash of every saved file) and FILES, each saved file
    with its own short hash, so a new version only downloads the files that changed."""
    import rjsmin
    files = offline_files()
    digest, hashes = hashlib.sha256(), {}
    for url, path in files.items():
        data = path.read_bytes()
        digest.update(url.encode() + b"\0" + data + b"\0")
        hashes[url] = hashlib.sha256(data).hexdigest()[:10]
    js = (SRC / "sw.js").read_text(encoding="utf-8")
    head = f'var VERSION="{digest.hexdigest()[:16]}",FILES={json.dumps(hashes, separators=(",", ":"))};\n'
    return banner("sw.js") + head + rjsmin.jsmin(js).strip() + "\n"


def build_fonts():
    from fontTools import subset
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer
    for name, (low, high) in FONTS.items():
        font = TTFont(SRC / "fonts" / name)
        font = instancer.instantiateVariableFont(font, {"wght": (low, high)})
        buf = io.BytesIO()
        font.flavor = None
        font.save(buf)  # save and reload so the subsetter sees a clean font
        font = TTFont(io.BytesIO(buf.getvalue()))
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.hinting = False
        opts.name_IDs = ["*"]  # keep the font's name and licence text
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=subset.parse_unicodes(UNICODES.replace(" ", "")))
        sub.subset(font)
        out = ROOT / "fonts" / name
        font.flavor = "woff2"
        font.save(out)
        print(f"fonts/{name}: {out.stat().st_size:,} bytes")


def main():
    check = "--check" in sys.argv
    stale = 0
    for name, text in minified().items():
        path = ROOT / name
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == text:
            continue
        if check:
            print(f"{name} does not match src/{name}. Run: python3 tools/build.py")
            stale += 1
        else:
            path.write_text(text, encoding="utf-8")
            print(f"{name}: {len(text.encode()):,} bytes (source {len((SRC / name).read_bytes()):,})")
    if "--fonts" in sys.argv and not check:
        build_fonts()
    if (SRC / "loopy.css").read_text(encoding="utf-8").count(f"unicode-range: {UNICODES};") != len(FONTS):
        print("The unicode-range of the -latin fonts in src/loopy.css does not match UNICODES in tools/build.py.")
        stale += 1
    csp = subprocess.run([sys.executable, str(ROOT / "tools" / "csp.py")] + (["--check"] if check else []))
    # Last, because its hash covers the files written above and the pages csp.py just updated.
    sw, path = service_worker(), ROOT / "sw.js"
    if (path.read_text(encoding="utf-8") if path.exists() else "") != sw:
        if check:
            print("sw.js is out of date (a saved file or src/sw.js changed). Run: python3 tools/build.py")
            stale += 1
        else:
            path.write_text(sw, encoding="utf-8")
            print(f"sw.js: {len(sw.encode()):,} bytes, saves {len(offline_files())} files for offline use")
    if check and not stale:
        print("loopy.js, loopy.css and sw.js match their sources in src/.")
    sys.exit(1 if stale or csp.returncode else 0)


if __name__ == "__main__":
    main()
