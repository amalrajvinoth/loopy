#!/usr/bin/env python3
"""Is the loopy plugin still in step with the repo?

    python3 plugins/loopy/scripts/drift.py            report; exit 1 if the plugin is behind
    python3 plugins/loopy/scripts/drift.py --update   record the repo as it is now (after updating the plugin)

The plugin's skills and hooks know facts about the repo: which checks CI runs, which tools exist,
which files are built, the pull request template, the screen sizes, how many GAMES lists a new game
goes in. When a later change moves one of these, this script names it and the skill or hook that
must learn it. That is what keeps the plugin evolving with the repo: CI runs this check, the Stop
hook runs it, and the evolve skill fixes what it finds and then runs --update.

facts.json holds the facts as they were last learned.
"""
import json, pathlib, re, subprocess, sys

PLUGIN = pathlib.Path(__file__).resolve().parent.parent
ROOT = PLUGIN.parent.parent
FACTS = PLUGIN / "facts.json"

# fact -> what in the plugin depends on it
USERS = {
    "ci_steps": "skills ship-pr and heal (the checks they run) and heal/recipes.md",
    "tools": "skills ship-pr and heal (the tools they run)",
    "repo_skills": "skill ship-pr (which repo skills to use) and RULES.md",
    "built_files": "hooks/guard_files.py and scripts/resolve_built.py (BUILT), RULES.md",
    "pr_template": "skill ship-pr (the PR body sections)",
    "screens": "RULES.md, scripts/screens.mjs (SIZES) and agents/screens.md",
    "games_lists": "skill new-game and RULES.md (how many GAMES lists a new game id goes in)",
}


def read(rel):
    p = ROOT / rel
    return p.read_text(encoding="utf-8") if p.is_file() else ""


def plugin_skill_names():
    return {p.parent.name for p in (ROOT / "plugins").glob("*/skills/*/SKILL.md")}


def current():
    steps = []
    for wf in sorted((ROOT / ".github/workflows").glob("*.yml")):
        for m in re.finditer(r"^\s*-?\s*name:\s*(.+)$", wf.read_text(encoding="utf-8"), re.M):
            steps.append(f"{wf.name}: {m.group(1).strip()}")
    tools = sorted(str(p.relative_to(ROOT)) for pat in ("tools/*.py", "tools/*/*.mjs", "tools/*/*.py") for p in ROOT.glob(pat))
    skills = sorted(p.parent.name for p in (ROOT / ".claude/skills").glob("*/SKILL.md") if p.parent.name not in plugin_skill_names())
    built = sorted(p.name for p in ROOT.iterdir() if p.is_file() and p.suffix in (".js", ".css")
                   and "Do not edit this file" in p.read_text(encoding="utf-8", errors="ignore")[:300])
    template = re.findall(r"^## (.+)$", read(".github/pull_request_template.md"), re.M)
    design = read("DESIGN.md")
    screens = sorted(set(re.findall(r"\|\s*(\d{3,4} × \d{3,4})\s*\|", design)))
    games_lists = len(re.findall(r"\bGAMES\s*=\s*\[", read("src/loopy.js")))
    return {"ci_steps": steps, "tools": tools, "repo_skills": skills, "built_files": built,
            "pr_template": template, "screens": screens, "games_lists": games_lists}


def self_checks(now):
    """Facts the plugin's own code repeats: they must match the repo, not just facts.json."""
    out = []
    for rel in ("hooks/guard_files.py", "scripts/resolve_built.py"):
        m = re.search(r"^BUILT\s*=\s*[\[{](.*?)[\]}]", (PLUGIN / rel).read_text(encoding="utf-8"), re.M)
        listed = sorted(re.findall(r'"([^"]+)"', m.group(1))) if m else []
        if listed != now["built_files"]:
            out.append(f"plugins/loopy/{rel}: BUILT lists {listed}, but the built files are {now['built_files']}.")
    m = re.search(r"const SIZES = \[(.*?)\];", (PLUGIN / "scripts/screens.mjs").read_text(encoding="utf-8"), re.S)
    sizes = sorted(f"{w} × {h}" for w, h in re.findall(r"\[(\d+),\s*(\d+)", m.group(1))) if m else []
    if sizes != now["screens"]:
        out.append(f"plugins/loopy/scripts/screens.mjs: SIZES are {sizes}, but DESIGN.md lists {now['screens']}.")
    return out


def main():
    now = current()
    if "--update" in sys.argv:
        head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
        FACTS.write_text(json.dumps({**now, "learned_at": head}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"Recorded the repo as the plugin knows it now (at {head}).")
        return 0
    known = json.loads(FACTS.read_text(encoding="utf-8")) if FACTS.is_file() else {}
    problems = []
    for key, value in now.items():
        old = known.get(key)
        if old == value:
            continue
        if isinstance(value, list) and isinstance(old, list):
            added, gone = [v for v in value if v not in old], [v for v in old if v not in value]
            what = "; ".join(x for x in (("new: " + ", ".join(added)) if added else "",
                                         ("gone: " + ", ".join(gone)) if gone else "") if x) or "order changed"
        else:
            what = f"was {old}, now {value}"
        problems.append(f"{key} changed ({what}). Update {USERS[key]}.")
    problems += self_checks(now)
    if not problems:
        if "--quiet" not in sys.argv:
            print("The loopy plugin is in step with the repo.")
        return 0
    print("The loopy plugin is behind the repo. Use the evolve skill (or fix by hand), then run "
          "python3 plugins/loopy/scripts/drift.py --update:")
    for p in problems:
        print(" - " + p)
    return 1


if __name__ == "__main__":
    sys.exit(main())
