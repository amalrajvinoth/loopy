#!/usr/bin/env python3
"""Tests for the plugin hooks and scripts. Each one feeds a hook what Claude Code would send it.

    python3 plugins/test_hooks.py      (exit 1 if any test fails; CI runs it)

Add a case here whenever a hook learns a new rule.
"""
import json, os, pathlib, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
WS, LP = ROOT / "plugins/work-style/hooks", ROOT / "plugins/loopy/hooks"
failed = []


def hook(script, payload, project=ROOT):
    env = {**os.environ, "CLAUDE_PROJECT_DIR": str(project)}
    env.pop("CLAUDE_PLUGIN_ROOT", None)
    p = subprocess.run([sys.executable, str(script)], input=json.dumps(payload), capture_output=True, text=True, env=env, cwd=project)
    return p.returncode, p.stdout + p.stderr


def expect(name, got, want):
    if got != want:
        failed.append(f"{name}: expected {want!r}, got {got!r}")


def blocked(script, payload, **kw):
    return hook(script, payload, **kw)[0] == 2


# The attribution text is built from parts so this file can itself be written by a guarded session.
CO, SESSION, GEN = "Co-Authored-" + "By: Claude", "Claude-" + "Session:", "Generated " + "with [Claude Code]"

# --- no Claude attribution -------------------------------------------------------------------
na = WS / "no_attribution.py"
bash = lambda c: {"tool_name": "Bash", "tool_input": {"command": c}}
expect("commit with Co-Authored-By Claude", blocked(na, bash(f'git commit -m "Fix\n\n{CO} Opus <noreply@anthropic.com>"')), True)
expect("commit after cd", blocked(na, bash(f"cd repo && git commit -m 'x' -m '{SESSION} https://claude.ai/code/session_1'")), True)
expect("commit from a heredoc file", blocked(na, bash(f"git commit -F - <<'EOF'\nFix\n\n{CO} <x>\nEOF")), True)
expect("plain commit", blocked(na, bash('git commit -m "Spell It: bigger letters"')), False)
expect("non-git command mentioning it", blocked(na, bash(f"grep -r '{CO}' .")), False)
expect("writing a file that mentions git commit", blocked(na, bash(f"cat > t.py <<'EOF'\nx = 'git commit {CO}'\nEOF")), False)
pr = lambda body: {"tool_name": "mcp__github__create_pull_request", "tool_input": {"title": "x", "body": body}}
expect("PR with Generated with Claude Code", blocked(na, pr(f"Changes\n\n🤖 {GEN}(https://claude.com/claude-code)")), True)
expect("PR with session link", blocked(na, pr("https://claude.ai/code/" + "session_013t8EBw")), True)
expect("PR with only the Requested by line", blocked(na, pr("_Requested by **Amal** · [project thread](https://claude.ai/code/project/chan_1?thread=c)_")), False)
expect("comment with Generated by Claude Code", blocked(na, {"tool_name": "mcp__github__add_issue_comment",
       "tool_input": {"body": "ok\n---\n_Generated " + "by [Claude Code](https://claude.ai/code)_"}}), True)

# --- new rule catcher -------------------------------------------------------------------------
cr = WS / "catch_rule.py"
expect("rule noticed", "standing rule" in hook(cr, {"prompt": "From now on always add a German name"})[1], True)
expect("update memory noticed", "standing rule" in hook(cr, {"prompt": "Update memory and global instructions to remove Claude attributions"})[1], True)
expect("plain ask ignored", hook(cr, {"prompt": "Take next task"})[1].strip(), "")

# --- built files and page safety --------------------------------------------------------------
gf = LP / "guard_files.py"
edit = lambda path, new: {"tool_name": "Edit", "tool_input": {"file_path": str(ROOT / path), "old_string": "a", "new_string": new}}
write = lambda path, text: {"tool_name": "Write", "tool_input": {"file_path": str(ROOT / path), "content": text}}
expect("edit built loopy.js", blocked(gf, edit("loopy.js", "x")), True)
expect("edit built sw.js", blocked(gf, edit("sw.js", "x")), True)
expect("edit src/loopy.js", blocked(gf, edit("src/loopy.js", "x")), False)
expect("style= in a page", blocked(gf, write("math/x/index.html", '<div class="a" sty' 'le="color:red">')), True)
expect("onclick= in a page", blocked(gf, edit("index.html", '<button on' 'click="go()">')), True)
expect("data-onclick is fine", blocked(gf, edit("index.html", '<button data-onclick="go">')), False)
expect("words 'one = two' are fine", blocked(gf, edit("index.html", "<p>one = two</p>")), False)
expect("style= in a .md file is fine", blocked(gf, write("README.md", 'Do not use sty' 'le="x"')), False)
expect("file outside the repo", blocked(gf, {"tool_name": "Write", "tool_input": {"file_path": "/tmp/x/loopy.js", "content": "x"}}), False)


# --- a tiny fake loopy repo for the merge and heal hooks --------------------------------------
def fake_repo(tmp):
    r = pathlib.Path(tmp)
    git = lambda *a: subprocess.run(["git", *a], cwd=r, capture_output=True, text=True, check=True)
    (r / "tools").mkdir(); (r / "src").mkdir()
    # build.py stand-in: --check fails unless loopy.js says "built"; a build writes "built".
    (r / "tools/build.py").write_text(
        "import pathlib, sys\np = pathlib.Path(__file__).resolve().parent.parent / 'loopy.js'\n"
        "if '--check' in sys.argv: sys.exit(0 if p.read_text() == 'built\\n' else 1)\np.write_text('built\\n')\n")
    for t in ("check_external.py", "review.py"):
        (r / "tools" / t).write_text("")
    (r / "src/loopy.js").write_text("src\n")
    meta = '<meta http-equiv="Content-Security-Policy" content="{}">\n'
    (r / "page.html").write_text("<html>\n" + meta.format("a") + "<p>hi</p>\n")
    (r / "other.html").write_text("<p>one</p>\n")
    (r / "loopy.js").write_text("built\n")
    git("init", "-q", "-b", "main"); git("config", "user.email", "t@t"); git("config", "user.name", "t")
    git("add", "."); git("commit", "-qm", "base")
    git("checkout", "-qb", "side")
    (r / "page.html").write_text("<html>\n" + meta.format("side") + "<p>hi</p>\n")
    (r / "other.html").write_text("<p>side</p>\n")
    (r / "loopy.js").write_text("side build\n")
    git("commit", "-qam", "side")
    git("checkout", "-q", "main")
    (r / "page.html").write_text("<html>\n" + meta.format("main") + "<p>hi</p>\n")
    (r / "other.html").write_text("<p>main</p>\n")
    (r / "loopy.js").write_text("main build\n")
    git("commit", "-qam", "main")
    return r


with tempfile.TemporaryDirectory() as tmp:
    r = fake_repo(tmp)
    subprocess.run(["git", "merge", "side"], cwd=r, capture_output=True)
    code, out = hook(LP / "after_merge.py", bash("git merge side"), project=r)
    unmerged = subprocess.run(["git", "diff", "--name-only", "--diff-filter=U"], cwd=r, capture_output=True, text=True).stdout.split()
    expect("merge: built file and policy-only page resolved, real conflict left", sorted(unmerged), ["other.html"])
    expect("merge: loopy.js rebuilt", (r / "loopy.js").read_text(), "built\n")
    expect("merge: page has no conflict markers", "<<<<<<<" in (r / "page.html").read_text(), False)
    expect("merge: hook tells Claude what is left", "other.html" in out, True)
    expect("merge: non-merge command ignored", hook(LP / "after_merge.py", bash("ls"), project=r)[1], "")

with tempfile.TemporaryDirectory() as tmp:
    r = fake_repo(tmp)
    (r / "loopy.js").write_text("stale\n")  # changed and out of date
    code, out = hook(LP / "heal.py", {"stop_hook_active": False}, project=r)
    expect("heal: blocks and says it rebuilt", '"decision": "block"' in out and "Healed" in out, True)
    expect("heal: loopy.js rebuilt", (r / "loopy.js").read_text(), "built\n")
    expect("heal: second stop in a row is let through", hook(LP / "heal.py", {"stop_hook_active": True}, project=r)[1], "")

with tempfile.TemporaryDirectory() as tmp:
    expect("heal: other projects are left alone", hook(LP / "heal.py", {}, project=pathlib.Path(tmp))[1], "")
    expect("guard: other projects are left alone", hook(gf, {"tool_name": "Write", "tool_input": {"file_path": tmp + "/loopy.js", "content": "x"}},
                                                        project=pathlib.Path(tmp))[0], 0)

if failed:
    print("Plugin hook tests failed:\n - " + "\n - ".join(failed))
    sys.exit(1)
print("All plugin hook tests pass.")
